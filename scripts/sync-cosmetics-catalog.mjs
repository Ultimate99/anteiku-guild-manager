import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ACCEPTED_EXTENSIONS = new Set(['.png', '.webp']);
const KEY_PATTERN = /^[A-Za-z0-9](?:[A-Za-z0-9_]{1,62}[A-Za-z0-9])$/;

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');
const migrationsDir = path.join(projectRoot, 'supabase', 'migrations');

const dryRun = process.argv.includes('--dry-run');

function pad(value) {
  return String(value).padStart(2, '0');
}

function formatTimestamp(date) {
  return [
    date.getFullYear(),
    pad(date.getMonth() + 1),
    pad(date.getDate()),
    pad(date.getHours()),
    pad(date.getMinutes()),
    pad(date.getSeconds()),
  ].join('');
}

function addSeconds(date, seconds) {
  return new Date(date.getTime() + seconds * 1000);
}

function sqlString(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function isManualAvatarKey(key) {
  return key.toLowerCase().includes('premium');
}

function isManualFrameKey(key) {
  return key.startsWith('TXK_Arena') || key.startsWith('TXK_KOF');
}

function getUnlockType(type, key) {
  if (key.endsWith('_FREE')) {
    return 'free';
  }

  if (type === 'avatar') {
    return isManualAvatarKey(key) ? 'manual' : 'free';
  }

  if (type === 'frame') {
    return isManualFrameKey(key) ? 'manual' : 'free';
  }

  return 'manual';
}

function getRarity(unlockType) {
  return unlockType === 'free' ? 'common' : 'rare';
}

async function collectCosmetics(type, folderName) {
  const directory = path.join(projectRoot, 'public', 'cosmetics', folderName);
  const entries = await readdir(directory, { withFileTypes: true });
  const ignored = [];
  const cosmetics = [];

  for (const entry of entries) {
    if (entry.name.startsWith('.')) {
      ignored.push(entry.name);
      continue;
    }

    if (!entry.isFile()) {
      ignored.push(entry.name);
      continue;
    }

    const extension = path.extname(entry.name).toLowerCase();

    if (!ACCEPTED_EXTENSIONS.has(extension)) {
      ignored.push(entry.name);
      continue;
    }

    const key = path.basename(entry.name, extension);

    if (!KEY_PATTERN.test(key)) {
      throw new Error(
        `Invalid cosmetic key "${key}" from ${folderName}/${entry.name}. Use 3-64 characters: letters, numbers, and underscores only.`,
      );
    }

    const unlockType = getUnlockType(type, key);

    cosmetics.push({
      key,
      type,
      labelKey: `cosmetics.${type}.${key}`,
      assetPath: `/cosmetics/${folderName}/${entry.name}`,
      rarity: getRarity(unlockType),
      unlockType,
      fileName: entry.name,
    });
  }

  cosmetics.sort((left, right) => left.fileName.localeCompare(right.fileName, 'en', { sensitivity: 'base' }));

  return { cosmetics, ignored };
}

function buildMigrationSql(rows) {
  const values = rows
    .map((row) =>
      [
        '    (',
        [
          `${sqlString(row.key)}::text`,
          `${sqlString(row.type)}::text`,
          `${sqlString(row.labelKey)}::text`,
          `${sqlString(row.assetPath)}::text`,
          `${sqlString(row.rarity)}::text`,
          `${sqlString(row.unlockType)}::text`,
          'true::boolean',
          `${row.sortOrder}::integer`,
        ].join(', '),
        ')',
      ].join(''),
    )
    .join(',\n');

  return `-- Anteiku Guild Manager - Cosmetics catalog sync
-- Generated by scripts/sync-cosmetics-catalog.mjs.
-- Review before applying through the normal staging and production migration gates.
-- This migration upserts discovered repo-backed cosmetics only.
-- It does not delete or deactivate catalog rows for missing files.

with synced_cosmetics (
  key,
  type,
  label_key,
  asset_path,
  rarity,
  unlock_type,
  is_active,
  sort_order
) as (
  values
${values}
)
insert into public.cosmetic_catalog (
  key,
  type,
  label_key,
  asset_path,
  rarity,
  unlock_type,
  is_active,
  sort_order
)
select
  key,
  type,
  label_key,
  asset_path,
  rarity,
  unlock_type,
  is_active,
  sort_order
from synced_cosmetics
on conflict (key) do update
set
  label_key = excluded.label_key,
  asset_path = excluded.asset_path,
  type = excluded.type,
  rarity = excluded.rarity,
  unlock_type = excluded.unlock_type,
  is_active = excluded.is_active,
  sort_order = excluded.sort_order,
  updated_at = now();
`;
}

async function getMigrationPath() {
  const now = new Date();

  for (let offset = 0; offset < 120; offset += 1) {
    const timestamp = formatTimestamp(addSeconds(now, offset));
    const migrationPath = path.join(migrationsDir, `${timestamp}_cosmetics_catalog_sync.sql`);

    try {
      await readdir(migrationPath);
    } catch (error) {
      if (error.code === 'ENOTDIR') {
        continue;
      }

      if (error.code === 'ENOENT') {
        return migrationPath;
      }

      throw error;
    }
  }

  throw new Error('Could not find an unused migration timestamp within 120 seconds.');
}

async function main() {
  const avatarResult = await collectCosmetics('avatar', 'avatars');
  const frameResult = await collectCosmetics('frame', 'frames');
  const rows = [...avatarResult.cosmetics, ...frameResult.cosmetics].map((row, index) => ({
    ...row,
    sortOrder: (index + 1) * 10,
  }));
  const ignored = [...avatarResult.ignored, ...frameResult.ignored];

  console.log(`Detected avatars: ${avatarResult.cosmetics.length}`);
  console.log(`Detected frames: ${frameResult.cosmetics.length}`);
  console.log(`Detected total cosmetics: ${rows.length}`);

  if (ignored.length > 0) {
    console.log(`Ignored entries: ${ignored.join(', ')}`);
  }

  if (rows.length === 0) {
    console.warn('No cosmetics assets found. No migration was generated.');
    return;
  }

  const sql = buildMigrationSql(rows);
  const migrationPath = await getMigrationPath();

  if (dryRun) {
    console.log(`Dry run only. Migration would be written to: ${path.relative(projectRoot, migrationPath)}`);
    console.log('\n--- SQL preview ---\n');
    console.log(sql);
    return;
  }

  await writeFile(migrationPath, sql, { flag: 'wx' });
  console.log(`Generated migration: ${path.relative(projectRoot, migrationPath)}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
